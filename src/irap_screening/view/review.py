"""Human review annotations: a reviewer's iRAP category for any attribute,
and a reviewer's own wording for a segment's recommendations.

Stored beside the route's own data (frames.csv, detections/, ...), not inside
out/ or view/: both of those are wholly regenerated by `irap report` / `irap
view`, and a review recorded there would be silently wiped by the next run.
This file is purely an annotation layer -- it never feeds back into
report.json, report.md or gap-check.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

# The iRAP categories a reviewer may code per attribute, and the flag each
# implies. Curvature splits at category 1/2 to match curvature.threshold_m
# (800 m); change both together. Condition has no Medium flag to map to, as
# the pipeline has no watch band, so Medium counts as normal.
REVIEW_CATEGORIES: dict[str, dict[int, str]] = {
    "curvature": {1: "normal", 2: "critical", 3: "critical", 4: "critical"},
    "grade": {1: "normal", 4: "critical", 5: "critical"},
    "delineation": {1: "normal", 2: "critical"},
    "condition": {1: "normal", 2: "normal", 3: "critical"},
    "quality_of_curve": {1: "normal", 2: "critical", 3: "normal"},
}


def _review_path(route_dir: Path) -> Path:
    return Path(route_dir) / "review.json"


def load_review(route_dir: Path) -> dict[str, dict[str, dict]]:
    """segment_id -> module -> {category, flag, note, reviewed_at}. {} if never reviewed."""
    path = _review_path(route_dir)
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def save_review_entry(
    route_dir: Path, segment_id: str, module: str, category: int | None, note: str
) -> dict:
    """Record a reviewer's iRAP category for one segment/module, overwriting any
    prior entry for it. None means the reviewer could not assess it either.
    Raises KeyError for a module or category REVIEW_CATEGORIES does not list.
    """
    flag = "not_assessed" if category is None else REVIEW_CATEGORIES[module][category]
    data = load_review(route_dir)
    entry = {
        "category": category,
        "flag": flag,
        "note": note,
        "reviewed_at": datetime.now(UTC).isoformat(),
    }
    data.setdefault(segment_id, {})[module] = entry
    _review_path(route_dir).write_text(json.dumps(data, indent=1), encoding="utf-8")
    return entry


def save_recommendation_edit(route_dir: Path, segment_id: str, text: str) -> dict | None:
    """Record a reviewer's recommendation text for one segment, shown in place
    of gap-check's. Blank text drops the edit, so the generated one shows again.
    Kept under the "recommendation" key, beside the per-module reviews.
    """
    data = load_review(route_dir)
    reviews = data.setdefault(segment_id, {})
    entry = None
    if text.strip():
        entry = {"text": text.strip(), "reviewed_at": datetime.now(UTC).isoformat()}
        reviews["recommendation"] = entry
    else:
        reviews.pop("recommendation", None)
    _review_path(route_dir).write_text(json.dumps(data, indent=1), encoding="utf-8")
    return entry
